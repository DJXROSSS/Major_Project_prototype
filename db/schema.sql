-- CSE STUDENT PLACEMENT INTELLIGENCE SYSTEM - POSTGRESQL SCHEMA
-- ============================================================================

DO $$ BEGIN CREATE TYPE user_role AS ENUM ('ADMIN', 'TRAINER', 'STUDENT'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE readiness_status AS ENUM ('PR', 'NPR'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE skill_domain AS ENUM (
    'Programming & Problem Solving',
    'Core Computer Science',
    'Software Development',
    'Employability & Soft Skills'
); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE event_type AS ENUM ('EXAM', 'MOCK_INTERVIEW'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- 1. USERS TABLE (RBAC: ADMIN, TRAINER, STUDENT)
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role user_role NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. STUDENTS TABLE (Core Profile + Dynamic JSON Attributes)
CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL,
    roll_no VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    batch VARCHAR(20) DEFAULT '2022-2026',
    branch VARCHAR(50) DEFAULT 'CSE',
    cgpa DECIMAL(4,2) DEFAULT 0.00,
    readiness_status readiness_status DEFAULT 'NPR',
    persona_badges JSONB NULL,
    custom_profile_fields JSONB NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE SET NULL
);

-- 3. SKILL TAXONOMY TABLE (Admin adds "columns/parameters" as rows here)
CREATE TABLE IF NOT EXISTS skill_taxonomy (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(80) NOT NULL UNIQUE,
    domain_category skill_domain NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. IMPORT BATCHES TABLE (Audit log of every uploaded Excel/CSV sheet)
CREATE TABLE IF NOT EXISTS import_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by BIGINT NULL,
    event_type event_type NOT NULL,
    event_title VARCHAR(150) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    column_mapping_config JSONB NOT NULL,
    total_rows_processed INT DEFAULT 0,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_batch_uploader FOREIGN KEY (uploaded_by) REFERENCES users(user_id) ON DELETE SET NULL
);

-- 5. EVALUATION RECORDS TABLE (Preserves exact Excel row + qualitative feedback)
CREATE TABLE IF NOT EXISTS evaluation_records (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    overall_score_pct DECIMAL(5,2) DEFAULT 0.00,
    strengths TEXT NULL,
    weaknesses TEXT NULL,
    behavior_remarks TEXT NULL,
    raw_excel_row JSONB NOT NULL,
    custom_attributes JSONB NULL,
    evaluated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_batch FOREIGN KEY (batch_id) REFERENCES import_batches(batch_id) ON DELETE CASCADE,
    CONSTRAINT fk_eval_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE
);

-- 6. SKILL RATINGS TABLE (Normalized 0-100% scores for fast filtering & 360 charts)
CREATE TABLE IF NOT EXISTS skill_ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    score_percentage DECIMAL(5,2) NOT NULL CHECK (score_percentage >= 0 AND score_percentage <= 100),
    source_type event_type NOT NULL,
    source_id BIGINT NOT NULL,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rating_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_rating_skill FOREIGN KEY (skill_id) REFERENCES skill_taxonomy(skill_id) ON DELETE CASCADE,
    CONSTRAINT fk_rating_record FOREIGN KEY (source_id) REFERENCES evaluation_records(record_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_skill_student ON skill_ratings(student_id, skill_id);
CREATE INDEX IF NOT EXISTS idx_skill_score ON skill_ratings(skill_id, score_percentage);

-- 7. COMPANY ROLES TABLE (Weighted skill requirements for Infosys, Cognizant, etc.)
CREATE TABLE IF NOT EXISTS company_roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(100) NOT NULL,
    role_title VARCHAR(100) NOT NULL,
    package_lpa DECIMAL(5,2) DEFAULT 0.00,
    min_cgpa DECIMAL(4,2) DEFAULT 6.00,
    skill_weights JSONB NOT NULL,
    skill_cutoffs JSONB NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Keep updated_at current when a student profile changes.

CREATE OR REPLACE FUNCTION set_students_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS students_updated_at ON students;
CREATE TRIGGER students_updated_at
    BEFORE UPDATE ON students
    FOR EACH ROW EXECUTE FUNCTION set_students_updated_at();
