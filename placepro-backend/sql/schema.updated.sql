-- 1. USERS TABLE (RBAC: ADMIN, TRAINER, STUDENT)
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role user_role NOT NULL,
    title VARCHAR(100) DEFAULT 'Member',
    status account_status DEFAULT 'active',
    last_active TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 1B. ACADEMIC BATCHES TABLE (For /api/v1/batches)
CREATE TABLE IF NOT EXISTS academic_batches (
    academic_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,           -- e.g. '2022–2026 CSE'
    department VARCHAR(120) NOT NULL,            -- e.g. 'Computer Science & Engineering'
    academic_years VARCHAR(40) NOT NULL,         -- e.g. '2022 – 2026'
    sections JSONB DEFAULT '["A", "B"]'::jsonb,
    trainer_ids JSONB DEFAULT '[]'::jsonb,       -- Array of user_ids
    status batch_status DEFAULT 'active',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. STUDENTS TABLE (Core Profile + Dynamic JSON Attributes)
CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL UNIQUE,
    academic_batch_id BIGINT NULL,
    roll_no VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    batch VARCHAR(50) DEFAULT '2022-2026',
    branch VARCHAR(50) DEFAULT 'CSE',
    section VARCHAR(10) DEFAULT 'A',
    cgpa DECIMAL(4,2) DEFAULT 0.00,
    average_score DECIMAL(5,2) DEFAULT 0.00,
    readiness_status readiness_status DEFAULT 'NPR',
    persona_badges JSONB NULL,
    custom_profile_fields JSONB NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_student_acad_batch FOREIGN KEY (academic_batch_id) REFERENCES academic_batches(academic_batch_id) ON DELETE SET NULL
);

-- 3. SKILL TAXONOMY TABLE
CREATE TABLE IF NOT EXISTS skill_taxonomy (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_code VARCHAR(40) NOT NULL UNIQUE,      -- e.g. 'dsa', 'dbms', 'comm'
    skill_name VARCHAR(80) NOT NULL UNIQUE,
    domain_category skill_domain NOT NULL,
    description TEXT DEFAULT '',
    parameter_type param_type DEFAULT 'numeric',
    is_active BOOLEAN DEFAULT TRUE,
    deleted_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. IMPORT BATCHES TABLE (Serves both /assessment-imports and /assessments)
CREATE TABLE IF NOT EXISTS import_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by BIGINT NULL,
    academic_batch_id BIGINT NULL,
    event_type event_type NOT NULL,
    event_title VARCHAR(150) NOT NULL,
    event_date DATE DEFAULT CURRENT_DATE,
    original_filename VARCHAR(255) NOT NULL,
    headers JSONB DEFAULT '[]'::jsonb,
    raw_preview_rows JSONB DEFAULT '[]'::jsonb,  -- Holds parsed sheet during PREVIEW
    validation_issues JSONB DEFAULT '[]'::jsonb,
    column_mapping_config JSONB DEFAULT '{}'::jsonb,
    total_rows_processed INT DEFAULT 0,
    import_status import_state DEFAULT 'PREVIEW',
    reviewed BOOLEAN DEFAULT FALSE,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_batch_uploader FOREIGN KEY (uploaded_by) REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_import_acad_batch FOREIGN KEY (academic_batch_id) REFERENCES academic_batches(academic_batch_id) ON DELETE SET NULL
);

-- Rows whose roll number did not match an existing student. They are retained
-- until an administrator creates the student or rejects the row.
CREATE TABLE IF NOT EXISTS import_student_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_batch_id BIGINT NOT NULL REFERENCES import_batches(batch_id) ON DELETE CASCADE,
    row_number INT NOT NULL,
    roll_no VARCHAR(50) NOT NULL,
    raw_row JSONB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (import_batch_id, roll_no)
);

