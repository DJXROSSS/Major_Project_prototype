    ON project_score_snapshots(project_id, computed_at DESC);

-- A student is PR only when the existing academic requirements and the
-- latest average of verified, approved project scores meet their cutoffs.
UPDATE students s
SET readiness_status = 'NPR'
WHERE s.readiness_status = 'PR'
  AND NOT EXISTS (
      SELECT 1
      FROM projects p
      JOIN LATERAL (
          SELECT final_score
          FROM project_score_snapshots
          WHERE project_id = p.project_id AND final_score IS NOT NULL
          ORDER BY computed_at DESC, project_score_snapshot_id DESC
          LIMIT 1
      ) latest ON TRUE
      JOIN LATERAL (
          SELECT review_status
          FROM project_reviews
          WHERE project_id = p.project_id
          ORDER BY created_at DESC, project_review_id DESC
          LIMIT 1
      ) review ON TRUE
      WHERE p.student_id = s.student_id
        AND p.ownership_status = 'VERIFIED'
        AND review.review_status = 'APPROVED'
      GROUP BY p.student_id
      HAVING AVG(latest.final_score) >= 60
  );

